const dimensions = (
  values: [number, number, number, number, number, number, number, number],
): ScoreDimension[] => {
  const names: ScoreDimension["name"][] = [
    "Social impact",
    "Technical fit",
    "Budget fit",
    "Timing fit",
    "Availability",
    "Delivery fit",
    "Commercial access",
    "Evidence confidence",
  ];
  const notes = [
    "Mission and public-value outcomes align with YipYip's preferred work.",
    "The likely scope matches product strategy, service design, and platform delivery capability.",
    "Funding evidence is useful, but the delivery budget still needs confirmation.",
    "The signal is fresh enough to create a realistic engagement window.",
    "The provisional start period fits the current capacity profile.",
    "The work appears suitable for direct delivery with a focused specialist partner if needed.",
    "A plausible route to a conversation exists before formal supplier selection.",
    "Claims are recent and traceable, with uncertainty retained where evidence is incomplete.",
  ];
  return names.map((name, index) => ({
    name,
    score: values[index],
    confidence: Math.min(0.96, 0.62 + values[index] * 0.035),
    explanation: notes[index],
  }));
};

